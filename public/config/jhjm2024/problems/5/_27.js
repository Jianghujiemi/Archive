const BCKE_output_sluts = [...new Set(
    BCKE_input_sluts
        .filter(input_slut => input_slut.replace("box", "cir"))
        .map(input_slut => input_slut.replace("box", "cir"))
        .filter(cir => cir[6] !== "0")
        .concat(["level_5_cir_0"])
)].sort().reverse();

function BCKE_operatorBox(cfg_0, cfg_1, in_str_0, in_str_1) {
    const expected_length_0 = cfg_0.poetry.length;
    let revealed_word_0;

    if (in_str_0 === "") {
        revealed_word_0 = "";
    } else if (in_str_0.length !== expected_length_0) {
        revealed_word_0 = null;
    } else {
        revealed_word_0 = cfg_0.position.map(pos_idx => in_str_0[pos_idx]).join(""); // "北风"
    }

    const expected_length_1 = cfg_1.poetry.length;
    let revealed_word_1;

    if (in_str_1 === "") {
        revealed_word_1 = "";
    } else if (in_str_1.length !== expected_length_1) {
        revealed_word_1 = null;
    } else {
        revealed_word_1 = cfg_1.position.map(pos_idx => in_str_1[pos_idx]).join(""); // "北风"
    }

    let revealed_word;
    if (revealed_word_0 === null || revealed_word_1 === null) {
        revealed_word = "错啦".substring(0, cfg_0.position.length);
    } else if (revealed_word_0 === "") {
        console.log(`empty revealed_word_0=${revealed_word_0}, return ${revealed_word_1}`);
        revealed_word = revealed_word_1;
    } else if (revealed_word_1 === "") {
        console.log(`empty revealed_word_0=${revealed_word_1}, return ${revealed_word_0}`);
        revealed_word = revealed_word_0;
    } else if (revealed_word_0 === revealed_word_1) {
        console.log(`hooray! ${revealed_word_0}`);
        revealed_word = revealed_word_0;
    } else {
        revealed_word = "错啦".substring(0, cfg_0.position.length);
    }

    return revealed_word;
}

function BCKE_refreshState(requestBody) {
    const retDict = {};

    for (const output_slut of BCKE_output_sluts) {
        const out_lvl = parseInt(output_slut[6]);
        const out_idx = parseInt(output_slut.substring(12));
        const in_lvl = out_lvl - 1;
        const in_idx_0 = 2 * out_idx;
        const in_idx_1 = 2 * out_idx + 1;
        const in_slut_0 = `level_${in_lvl}_box_${in_idx_0}`;
        const in_slut_1 = `level_${in_lvl}_box_${in_idx_1}`;

        const cfg_0 = BCKED[in_slut_0];
        const cfg_1 = BCKED[in_slut_1];
        const in_str_0 = requestBody[in_slut_0];
        const in_str_1 = requestBody[in_slut_1];
        const revealed_word = BCKE_operatorBox(cfg_0, cfg_1, in_str_0, in_str_1);
        retDict[output_slut] = revealed_word;
    }

    return retDict;
}

const BCKE_input_sluts = Object.keys(BCKED);



function BCKE_submit(req) {
    try {
        const body = typeof req === 'string' ? JSON.parse(req) : req;
        const retDict = BCKE_refreshState(body);

        return {
            error: "",
            ret_dict: retDict,
        };

    } catch (error) {
        console.error(error);

        return {
            error: "Error Occured. Please Contact Staff.",
            ret_dict: {},
        };
    }
}